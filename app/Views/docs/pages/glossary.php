<dl class="glossary">
<dt>Access ends on</dt><dd>The date a login stops working (a leaver’s last day). Checked on every request.</dd>
<dt>Active on a date</dt><dd>Started on or before the date, and not ended or ending on or after it.</dd>
<dt>Activity log</dt><dd>The append-only record of who changed what.</dd>
<dt>Administrator</dt><dd>The role that can do everything, including logins, modules and integrations.</dd>
<dt>Appraisal</dt><dd>A formal review of a member of staff’s performance, with an outcome and next due date.</dd>
<dt>Approval</dt><dd>A line manager or HR accepting a change a member of staff asked for on their own record.</dd>
<dt>Audit trail</dt><dd>See activity log.</dd>
<dt>Care need</dt><dd>Something a person we support needs help with, with a category, severity and review date.</dd>
<dt>Checklist</dt><dd>A template of tasks created when someone joins, changes role or leaves.</dd>
<dt>Consistency check</dt><dd>The safety net that finds data that disagrees with itself.</dd>
<dt>Contract type</dt><dd>For example permanent, fixed term, bank, apprentice.</dd>
<dt>Effective date</dt><dd>The day a change takes effect.</dd>
<dt>Employment</dt><dd>One stint of work. A rehire is a new employment for the same person.</dd>
<dt>Entra</dt><dd>Microsoft Entra ID, the identity service behind Microsoft 365 work accounts.</dd>
<dt>Event</dt><dd>A small record (“this person’s employment ended on this date”) made for every change and delivered to other systems.</dd>
<dt>Idempotency key</dt><dd>An id a receiver uses to recognise it has already handled something. Here, the event id.</dd>
<dt>Joiner</dt><dd>Someone starting work. Also the process that handles it.</dd>
<dt>Key worker</dt><dd>The member of staff who has particular responsibility for one person we support.</dd>
<dt>Last day</dt><dd>The final day of an employment, place or link. Inclusive.</dd>
<dt>Leaver</dt><dd>Someone ending work. Also the process that handles it.</dd>
<dt>Line manager</dt><dd>The person someone reports to. Can review that person’s requests.</dd>
<dt>Module</dt><dd>A switchable part of Care Core: People, Staff, Teams, Care.</dd>
<dt>Mover</dt><dd>Someone changing role, hours, line manager or team. Also the process.</dd>
<dt>OIDC</dt><dd>OpenID Connect, the standard behind “Sign in with Microsoft”.</dd>
<dt>Organisation</dt><dd>One customer of Care Core. Data is separate per organisation.</dd>
<dt>Outbox</dt><dd>The table of events waiting to be delivered.</dd>
<dt>Person</dt><dd>A human, recorded once and never deleted.</dd>
<dt>Person we support</dt><dd>Someone receiving care or support from your service.</dd>
<dt>PKCE</dt><dd>A protection for the sign-in code exchange.</dd>
<dt>Primary team</dt><dd>A member of staff’s main team.</dd>
<dt>Reassign task</dt><dd>A task created when a leaver leaves behind a key worker role or direct reports.</dd>
<dt>Registration</dt><dd>A professional registration, such as with the SSSC, with an expiry date.</dd>
<dt>Rehire</dt><dd>Someone who worked before starting again: a new employment, same person.</dd>
<dt>SCIM</dt><dd>A standard for pushing people from a directory like Entra into another system.</dd>
<dt>Signature</dt><dd>An image of a person’s signature, drawn or uploaded, for use on forms.</dd>
<dt>Staff only</dt><dd>A team that people we support cannot be added to.</dd>
<dt>Stint</dt><dd>One continuous period in a team.</dd>
<dt>Support episode</dt><dd>One continuous period of receiving support.</dd>
<dt>Supervision</dt><dd>A one-to-one or group meeting between a member of staff and a supervisor, with a next due date.</dd>
<dt>Task</dt><dd>A piece of follow-up work.</dd>
<dt>TUPE</dt><dd>Transfer of Undertakings (Protection of Employment): rules when staff transfer to a new employer.</dd>
<dt>UPN</dt><dd>User principal name: someone’s Microsoft sign-in name, usually their email.</dd>
<dt>Webhook</dt><dd>A web address that Care Core calls to tell another system about an event.</dd>
</dl>
