<p>The dashboard is the first page after you sign in. What it shows depends on your role.</p>

<h2>Managers and administrators</h2>
<h3>The four numbers</h3>
<ul>
<li><strong>Staff</strong>: people with an employment that is active today.</li>
<li><strong>People supported</strong>: people with a support episode that is active today (shown only when the Care module is on).</li>
<li><strong>Open tasks</strong> and <strong>Overdue</strong>: the work waiting, and how much of it is past its due date.</li>
</ul>
<h3>Starting soon and leaving soon</h3>
<p>Two lists show who starts and who leaves in the <strong>next 30 days</strong>, with their job title and date. Click a name to open their profile. This is where you notice, for example, that a leaver in three weeks is a key worker for two people.</p>
<h3>Tasks</h3>
<p>The first eight open tasks, oldest due first. The full list is on <a href="/docs/tasks">Tasks</a>.</p>
<h3>Needs attention</h3>
<p>The high-severity findings from the <a href="/docs/admin-reconcile">consistency checks</a>, if there are any. Normally this section is empty.</p>
<h3>Recent activity</h3>
<p>The last eight entries of the <a href="/docs/admin-activity">activity log</a> (managers and administrators).</p>

<h2>Staff</h2>
<p>Staff see a personal view: their job title, their team or teams, and a prompt to open <a href="/docs/my-profile">My profile</a>.</p>

<h2>The menu</h2>
<p>The top menu shows only what your role and your organisation’s modules allow: Dashboard, People, Teams, Tasks, My profile, Approvals (with a count when something is waiting), Activity, Admin and Help.</p>
