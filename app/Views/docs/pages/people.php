<p>The same person can appear under more than one filter. Someone who works for you and also receives support is listed under both. Staff-role users see staff only.</p>

<h2>A profile page</h2>
<p>Each person has one profile. It shows only what applies to them.</p>
<h3>Header</h3>
<p>Their name, job title, what they are (staff, former staff, person we support, or several), and the actions you may take: <strong>Edit details</strong>, <strong>Staff record</strong>, <strong>Change role or team</strong>, <strong>Record leaving</strong>, or <strong>Start new employment</strong> for a former member of staff.</p>
<h3>Details</h3>
<p>Email, phone, date of birth and notes.</p>
<h3>Employment</h3>
<p>Every stint of employment, newest first: role, contract and hours, employee reference, start date, last day and reason for leaving, and line manager. Under it, <strong>changes to the current role</strong> are listed with the date each took effect.</p>
<h3>Teams</h3>
<p>Every team place they have had, with role, start and end. The current main team is marked <em>Primary</em>.</p>
<h3>Care sections (managers, Care module on)</h3>
<p>Key workers (and who they are key worker for), support episodes, care needs, and contacts. See <a href="/docs/care">People we support</a>.</p>
<h3>Tasks and activity</h3>
<p>Tasks about this person, and the activity log entries about them.</p>

<h2>Editing basic details</h2>
<p><strong>Edit details</strong> (managers and administrators) changes first name, last name, “known as”, date of birth, email, phone and notes. Names are required. The date of birth cannot be in the future. The email must look like an email address. Changes are written to the activity log and announced as a <code>person.updated</code> event.</p>
<p>Everything else about a staff member (address, pay and tax, contract terms, compliance) is on the <a href="/docs/staff-record">staff record</a>.</p>
