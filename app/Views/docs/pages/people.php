<h2>The People page</h2>
<p>Everyone in your organisation is in one list: staff, people we support and former staff. Use the search box to find someone by <strong>first name, last name, full name or email address</strong>. Partial matches work, so “mac” finds Maclean and Macleod.</p>
<h3>Filters</h3>
