<h2>Line managers</h2>
<p>Whoever is recorded as a person’s line manager on their current employment can approve or decline that person’s requests (<a href="/docs/approvals">Reviewing approvals</a>) whatever their own role. The Approvals item appears in the menu for anyone who has something waiting.</p>

<h2>Things nobody can do</h2>
<ul>
<li><strong>Approve your own request.</strong> Even an administrator cannot review a change to their own record.</li>
<li><strong>Edit your own staff record through the manager page.</strong> A manager who opens their own staff record is sent to <em>My profile</em>, so their changes follow the same approval route as everyone else’s. (Administrators are the exception, so there is always someone who can correct a record.)</li>
<li><strong>See another organisation’s data.</strong></li>
<li><strong>Read National Insurance and bank details without being allowed to.</strong> They are visible only on the manager’s staff record page and, masked, to the person themselves.</li>
</ul>

