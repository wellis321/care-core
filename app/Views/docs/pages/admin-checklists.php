<p><strong>Admin › Checklists</strong> controls the tasks that are created automatically when someone joins, changes role or team, or leaves. There are three checklists: <em>New starter</em>, <em>Change of role or team</em> and <em>Leaver</em>. The defaults are listed in <a href="/docs/tasks">Tasks and checklists</a>.</p>

<h2>Each item has</h2>
<div class="tablewrap"><table>
<thead><tr><th>Field</th><th>Meaning</th></tr></thead>
<tbody>
<tr><td>Title</td><td>The task, for example “Return keys, ID badge and equipment”.</td></tr>
<tr><td>Owner role</td><td>Who should do it: administrator, manager or staff. Tasks owned by the staff role are visible to staff.</td></tr>
<tr><td>Due offset (days)</td><td>Days from the key date. <strong>Negative = before</strong>, 0 = on the day, positive = after. The key date is the start date for a joiner, the effective date for a mover and the last day for a leaver.</td></tr>
</tbody></table></div>

<h2>Adding and removing items</h2>
<p>Use the form under a checklist to add an item, and <strong>Remove</strong> against an item to delete it from the checklist.</p>
<div class="note"><strong>Changes apply going forward.</strong> Tasks that have already been created are not changed or removed when you edit a checklist. Only the next joiner, mover or leaver gets the new list.</div>

<h2>Making it fit your organisation</h2>
<p>The defaults reflect common practice in Scottish care services (PVG checks, SSSC registration). Replace them with your own. For example you might add “Order uniform”, “Add to rota system” or “Notify the Care Inspectorate of the change of manager”, and set the due dates and owners to match how you work.</p>
