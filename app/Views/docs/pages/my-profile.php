<p><strong>My profile</strong> is where each member of staff keeps their own details up to date. It is in the menu for everyone whose login is linked to a staff record. If yours is not linked, the page says so and tells you to ask your manager or HR.</p>

<h2>Two kinds of change</h2>
<div class="tablewrap"><table>
<thead><tr><th>Saves straight away</th><th>Goes to your line manager (or HR) first</th></tr></thead>
<tbody>
<tr><td>Phone number<br>Emergency contact name<br>Emergency contact phone</td><td>First name, last name, date of birth<br>Home address (all lines, town, county, postcode, country)<br>National Insurance number<br>Bank name, sort code, account number<br>Photo<br>Signature</td></tr>
</tbody></table></div>
<p>Emergency contact details apply at once because they might be needed urgently. Things that affect identity, payroll or the legal record wait for a second pair of eyes.</p>

<h2>Changing your details</h2>
<ol>
<li>Open <strong>My profile</strong>, change what you need, and choose <strong>Save my details</strong>.</li>
<li>Care Core checks each value (a phone number with letters, an impossible National Insurance number or a bad sort code are refused, with the message beside the field).</li>
<li>Fields that apply at once are saved. The others appear under <strong>Waiting for approval</strong>, showing the old value crossed out and the new one.</li>
<li>Until someone approves, the live record keeps the old value.</li>
</ol>
<p>You are told exactly what happened: “1 saved straight away, 2 sent to your line manager to approve”. If you submit what is already there, nothing changes.</p>

<h3>National Insurance and bank boxes are shown empty</h3>
<p>For safety these boxes do not show the stored value. The hint under each says what is held (for example “Currently ••••5678”). <strong>Leave a box empty to keep what is there.</strong> Type a new value to request a change.</p>

<h3>Changing your mind</h3>
<ul>
<li>Ask for the same field again and the earlier request is replaced.</li>
<li>Change a value back to what is already on record and the pending request is withdrawn.</li>
<li>Choose <strong>Withdraw</strong> beside any waiting request to cancel it.</li>
</ul>

<h2>Seeing the outcome</h2>
<p>When a request is approved or declined, a message appears at the top of <strong>My profile</strong> the next time you open it, with the reason if it was declined. It is shown once.</p>

<h2>Photo</h2>
<p>Choose a picture (PNG, JPEG, WebP or GIF, up to 3 MB) and <strong>Send photo</strong>. The new photo is shown next to your current one marked <em>Waiting for approval</em>. Only genuine images are accepted: a file that merely has a picture’s name is refused.</p>

<h2>Signature</h2>
<p>Your signature is used where forms and records need one. Two ways to add it:</p>
<ul>
<li><strong>Draw it</strong> in the box with a mouse, a finger or a pen. <strong>Clear</strong> starts again. It works on touch screens.</li>
<li><strong>Upload a picture</strong> of your signature (up to 1 MB).</li>
</ul>
<p>Choose <strong>Send signature</strong>. If you do neither, you are asked to draw it or choose a picture. It is held for approval like the photo. Once approved it becomes your live signature, with the date added and whether it was drawn or uploaded. A replaced signature file is deleted.</p>
<div class="note"><strong>Who can see your signature?</strong> You, your line manager, managers and administrators. Photos can be seen by anyone signed in to your organisation, because they are shown on staff lists and profiles.</div>

<h2>Everything else on the page</h2>
<ul>
<li><strong>My job:</strong> role, start date, who you report to and your team. Your manager or HR keeps these up to date.</li>
<li><strong>Registrations, supervisions, appraisals, learning:</strong> your most recent entries, read-only.</li>
</ul>
