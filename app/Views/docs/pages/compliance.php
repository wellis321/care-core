<h2>Appraisals</h2>
<p>Date, appraiser, type (annual, probationary, interim, return to work, other), <strong>outcome</strong> (pending, outstanding, exceeds expectations, meets expectations, requires improvement, unsatisfactory, not completed), next due date and notes.</p>

<h2>Learning and qualifications</h2>
<p>Training, qualifications, courses, certifications and induction. Title (required), kind, provider, level, completed and expiry dates (expiry cannot be before completion), certificate number, status (completed, in progress, pending, expired), whether it is <strong>mandatory training</strong>, and notes.</p>

<h2>Adding and removing</h2>
<p>Fill in the form under a list and choose <strong>Add</strong>. Anything wrong is shown above the form and nothing is saved until it is right. To remove a record, choose <strong>Remove</strong> on its row. Each add and remove is written to the activity log. Editing a record in place is not available yet: remove it and add the corrected one. Each addition also creates an event (for example <code>registration.recorded</code>) carrying the record id and its due date.</p>

<h2>What is due soon</h2>
<p>Care Core can list everything that is <strong>overdue or due in the next 60 days</strong> across the organisation:</p>
<ul>
<li>registrations and training that <strong>expire</strong>;</li>
<li>supervisions and appraisals whose <strong>next due</strong> date is near or past. Only the <em>most recent</em> supervision and appraisal for each person counts, so an old due date that was later met does not show.</li>
</ul>
<p>Only people with a <strong>current employment</strong> are included, so leavers never clutter the list. Each row says what it is, who it is about, and whether it is overdue.</p>

<h2>Who sees these records</h2>
<p>Managers and administrators can read and change them. Each member of staff can read their own on <a href="/docs/my-profile">My profile</a> (the most recent few of each kind). They cannot change them.</p>
