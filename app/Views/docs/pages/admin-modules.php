<p><strong>Admin › Modules</strong> switches parts of Care Core on and off for your organisation.</p>
<div class="tablewrap"><table>
<thead><tr><th>Module</th><th>When it is off</th></tr></thead>
<tbody>
<tr><td><strong>People</strong></td><td>Cannot be switched off. It is the core: people, profiles, logins, tasks, the activity log.</td></tr>
<tr><td><strong>Staff</strong></td><td>The joiner, mover and leaver pages, the staff record and its links are hidden and return “not switched on”.</td></tr>
<tr><td><strong>Teams</strong></td><td>The Teams menu item and pages are hidden.</td></tr>
<tr><td><strong>Care</strong></td><td>People we support, key workers and care information are hidden, and the “People we support” filter disappears.</td></tr>
</tbody></table></div>
<h2>What switching off does not do</h2>
<ul>
<li>It <strong>does not delete</strong> anything. Switch the module back on and everything is there.</li>
<li>It does not stop the rules that connect modules from working. For example, ending someone’s employment still ends their team places even if the Teams menu is hidden.</li>
</ul>
<h2>When to use it</h2>
<p>If you only use Care Core to manage staff, switch Care off so people do not see sections they will never use. If you are a small provider with no team structure, switch Teams off.</p>
